// Copies the Zebra icon font (packages/icons) into src/generated/zebra-icons for glyphs Zeta's own font lacks.
// Usage: node scripts/zebra-icons.mjs [iconsDir] [outDir]   (yarn icons)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2] ?? "../icons";
const out = process.argv[3] ?? "src/generated/zebra-icons";
mkdirSync(out, { recursive: true });

for (const family of ["Rounded", "Sharp"]) {
  copyFileSync(
    join(src, "fonts", `ZdsIcons-${family}.woff2`),
    join(out, `ZdsIcons-${family}.woff2`),
  );
}

const header =
  "/* Generated by `yarn icons` from packages/icons. Do not edit. */\n";
writeFileSync(
  join(out, "zebra-icons.css"),
  header +
    ["Rounded", "Sharp"]
      .map(
        (family) => `@font-face {
  font-family: "ZdsIcons-${family}";
  src: url("./ZdsIcons-${family}.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}
`,
      )
      .join("\n"),
);

const { glyphs } = JSON.parse(
  readFileSync(join(src, "codepoints.json"), "utf8"),
);
const live = Object.entries(glyphs)
  .filter(([, g]) => !g.retired)
  .sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
  join(out, "glyphs.ts"),
  header.replace("/*", "//").replace(" */", "") +
    `\n/** Zebra icon names (kebab-case) mapped to their font character. */\nexport const zebraIconGlyphs: Record<string, string> = {\n` +
    live
      .map(
        ([name, g]) =>
          `  ${JSON.stringify(name)}: "\\u{${g.codepoint.toString(16)}}"`,
      )
      .join(",\n") +
    "\n};\n",
);
console.log(`zebra-icons: ${live.length} glyphs -> ${out}`);

"""Regenerate tokens.css, the six token CSS blocks PROTOTYPING.AGENTS.md describes. Maintainers only (needs Python 3).

Usage: python3 scripts/tokens-css.py
Reads the DESIGN.md frontmatter and the `tokens:` block of every component file, and writes tokens.css
at the repo root with every component in it. Rerun it after any change to DESIGN.md or a component's tokens.
Prototypes just link the finished file, so the people building them never run this.
"""
import re, sys, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONT = '"IBM Plex Sans", sans-serif'

def val(raw):
    raw = raw.strip()
    if raw[:1] in "'\"":
        q = raw[0]; return raw[1:raw.index(q, 1)]
    return raw.split(' #')[0].strip()

def parse_front(path):
    text = open(path).read().split('\n---\n')[0]
    groups, cur = {}, None
    for line in text.splitlines():
        if re.match(r'^[a-z-]+:', line):
            cur = line.split(':')[0]; groups[cur] = {}
        elif cur and re.match(r'^  [a-z0-9-]+:', line):
            k, v = line.strip().split(':', 1); groups[cur][k] = v.strip()
    return groups

g = parse_front(os.path.join(ROOT, 'DESIGN.md'))

def colors(group): return [f'  --{k}: {val(v)};' for k, v in g[group].items()]

def typo(v):
    if 'alias' in v: return f'var(--{re.search(r"alias: ([a-z-]+)", v).group(1)})'
    m = dict(re.findall(r"(\w+): '?([^,'}]+)'?", v))
    return f"{m['fontWeight']} {m['fontSize'].strip()}/{m['lineHeight'].strip()} {FONT}"

def dim(k, v):
    v = val(v)
    if k.endswith('-scale'): return str(float(v[:-1]) / 100) if v.endswith('%') else v
    m = re.fullmatch(r'(\d+) (\d+)/(\d+)', v)
    return f'{m[1]} {m[2]}px/{m[3]}px {FONT}' if m else v

root = colors('colors')
for grp in ['spacing', 'rounded', 'border', 'elevation', 'font-weight', 'motion', 'opacity']:
    root += [f'  --{k}: {val(v)};' for k, v in g[grp].items()]
root += [f'  --{k}: {val(v)};' for k, v in g['layout'].items() if re.fullmatch(r'[\d.]+px', val(v))]
root += [f'  --{k}: {typo(v)};' for k, v in g['typography'].items()]
root += [f'  --{k}: {dim(k, v)};' for k, v in g['dimensions'].items()]

# component tokens, following composes all the way down
files = {os.path.basename(p)[:-3]: os.path.join(ROOT, d, p) for d in ('atoms', 'molecules', 'organisms') for p in os.listdir(os.path.join(ROOT, d))}
seen, order = set(), []
def visit(name):
    if name in seen: return
    seen.add(name); fm = open(files[name]).read().split('\n---\n')[0]
    for child in re.findall(r'([a-z-]+)\.md', re.search(r'composes: \[(.*)\]', fm).group(1)): visit(child)
    order.append((name, fm))
for name in sorted(files): visit(name)  # every component; composed children are visited first
comp = []
for name, fm in order:
    comp.append(f'  /* {name} */')
    for k, v in re.findall(r"^  ([a-z0-9-]+): '\{[a-z-]+\.([a-z0-9-]+)\}'", fm, re.M):
        comp.append(f'  --{k}: var(--{v});')

hc, dark, light = colors('colors-high-contrast'), colors('colors-dark'), colors('colors')
css = '\n'.join([
  ':root {  /* 1. light colours + every non-colour token */', *root, '}',
  '[data-contrast="high"] {  /* 2. high contrast (light) */', *hc, '}',
  '[data-theme="dark"] {  /* 3. dark */', *dark, '}',
  '[data-theme="light"] {  /* 4. light inside a dark area */', *light, '}',
  '[data-contrast="high"] [data-theme="light"] {  /* 5. light area inside a high-contrast page */', *hc, '}',
  ':root, [data-theme], [data-contrast] {  /* 6. component tokens: ' + ', '.join(n for n, _ in order) + ' */', *comp, '}'])
with open(os.path.join(ROOT, 'tokens.css'), 'w') as f:
    f.write('/* Generated by scripts/tokens-css.py from DESIGN.md and the component files. Do not edit by hand. */\n' + css + '\n')
print(f'tokens.css: {len(order)} components, {css.count(chr(10))} lines')

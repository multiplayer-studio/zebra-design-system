"""Build prototypes/_starter/index.html, the page every prototype starts from, and refresh the showcase's marked blocks.
Maintainers only (Python 3, stdlib).

Usage: python3 scripts/starter-html.py
Rerun after tokens.css or icons.json is regenerated, or prototypes/_starter/components.css changes. Same inputs, same bytes.
The showcase (prototypes/showcase/index.html) gets the same tokens and components blocks, plus an icons block holding
the @font-face rules for the @zebra-fed/zeta-icons fonts (from jsDelivr, at icons.json's version) and every icon name.
Nothing outside its markers is touched.
It then reports drift between components.css and the tokens: var() names nothing defines, and component tokens
components.css never uses. Report-only: it lists them but never fails.

Why the tokens are inlined: the Claude desktop Browser pane loads a prototype as a data: document, so a relative
<link href="../../tokens.css"> never resolves. The starter carries tokens.css and components.css in marked blocks
instead; Claude refreshes a prototype by replacing what's between the markers. If the pane ever resolves relative
links, go back to linking tokens.css and drop this script.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _bundle import ROOT

read = lambda *p: open(os.path.join(ROOT, *p)).read()
version = re.search(r"^version:\s*'?([^'\n]+)", read('DESIGN.md'), re.M).group(1)
tokens = f"<style>\n/* tokens.css from Zebra Design System, DESIGN.md version {version} */\n{read('tokens.css').rstrip()}\n</style>"
components = f"<style>\n{read('prototypes', '_starter', 'components.css').rstrip()}\n</style>"
plex = '\n'.join(
    f'@font-face {{ font-family: "IBM Plex Sans"; font-weight: {w}; font-style: normal; font-display: swap; '
    f'src: url("https://cdn.jsdelivr.net/npm/@fontsource/ibm-plex-sans@5.3.0/files/ibm-plex-sans-latin-{w}-normal.woff2") format("woff2"); }}'
    for w in (300, 400, 500))

html = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Prototype</title>
<!-- Generated by scripts/starter-html.py. Tokens and components are inlined because the Claude desktop Browser pane
     loads pages as data: documents and ignores relative links such as ../../tokens.css. Refresh only between the markers. -->
<style>
{plex}
* {{ box-sizing: border-box; }}
[hidden] {{ display: none !important; }}
body {{ margin: 0; font: var(--type-body-medium); color: var(--color-ink-high); background: var(--color-fill-default); }}
h1, h2, h3, h4, h5, h6, p {{ margin: 0; }}
main {{ padding: var(--space-page); }}
</style>
<!-- tokens:start -->
{tokens}
<!-- tokens:end -->
<!-- components:start -->
{components}
<!-- components:end -->
</head>
<body>
</body>
</html>
'''
out = os.path.join(ROOT, 'prototypes', '_starter', 'index.html')
with open(out, 'w') as f:
    f.write(html)
print(f'prototypes/_starter/index.html: tokens from DESIGN.md {version}')

def fill(html, name, body):
    pattern = re.compile(rf'(<!-- {name}:start -->\n)(?:.*?\n)?(<!-- {name}:end -->)', re.S)
    assert len(pattern.findall(html)) == 1, f'showcase needs exactly one {name} block'
    return pattern.sub(lambda m: m[1] + body + '\n' + m[2], html)

icon_json = json.loads(read('icons.json'))
icon_cdn = f"https://cdn.jsdelivr.net/npm/{icon_json['package']}@{icon_json['version']}/outputs/web"
icons = '<style>\n/* the @zebra-fed/zeta-icons fonts, straight from the package */\n' + '\n'.join(
    f'@font-face {{ font-family: "zeta-icons-{s}"; font-display: block; src: url("{icon_cdn}/zeta-icons-{s}.woff2") format("woff2"); }}'
    for s in ('round', 'sharp')) + '\n</style>\n<script>\n// every icon name in the package (from icons.json)\nvar ICON_NAMES = ' + \
    json.dumps(list(icon_json['icons']), separators=(',', ':')) + ';\n</script>'
path = os.path.join(ROOT, 'prototypes', 'showcase', 'index.html')
html = open(path).read()
for name, body in (('tokens', tokens), ('components', components), ('icons', icons)):
    html = fill(html, name, body)
html = re.sub(r'Showcase · v[^<]*', f'Showcase · v{version}', html)  # header version follows DESIGN.md
with open(path, 'w') as f:
    f.write(html)
print('prototypes/showcase/index.html: tokens, components and icons blocks refreshed')

# Drift check between components.css and the tokens (report-only for now: it never fails the run).
#   undefined: var(--x) in components.css that neither tokens.css nor components.css itself defines
#              (renamed/removed tokens, or values a prototype's script or inline style must set)
#   unused:    component tokens (tokens.css section 7, grouped by component) that components.css never uses
css_src = read('prototypes', '_starter', 'components.css')
used = set(re.findall(r'var\(--([\w-]+)', css_src))
tokens_src = read('tokens.css')
defined = set(re.findall(r'--([\w-]+)\s*:', tokens_src)) | set(re.findall(r'--([\w-]+)\s*:', css_src))
undefined = sorted(used - defined)
unused, component = {}, None
for line in tokens_src.split('/* 7. component tokens', 1)[1].split('/* 8.', 1)[0].splitlines():
    m = re.match(r'\s*/\* ([a-z0-9-]+) \*/', line) or re.match(r'\s*--([\w-]+):', line)
    if not m: continue
    if line.lstrip().startswith('/*'): component = m[1]
    elif m[1] not in used: unused.setdefault(component, []).append(m[1])
print(f'drift check (report only): {len(undefined)} undefined, {sum(map(len, unused.values()))} unused component tokens')
if undefined: print('  undefined: ' + ', '.join('--' + n for n in undefined))
for name, names in unused.items():
    print(f'  unused in {name} ({len(names)}): ' + ', '.join('--' + n for n in names))

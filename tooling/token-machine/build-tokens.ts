async function main() {
  console.log('🚀 Starting Design Token Build Process...');
  if (fs.existsSync(TEMP_DIR)) fs.rmSync(TEMP_DIR, { recursive: true, force: true });
  fs.mkdirSync(TEMP_DIR, { recursive: true });
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  const themes = new Set<string>(['default']);
  const tokenFiles = await glob(`${TOKEN_DIR}/*.json`);
  tokenFiles.forEach(file => {
    const parts = path.basename(file, '.json').split('-');
    if (parts.length === 3 && !['base', 'value', ...COLOR_MODES, ...BREAKPOINT_MODES].includes(parts[1])) {
      themes.add(parts[1]);
    }
  });
  console.log(`🔍 Discovered Themes: ${Array.from(themes).join(', ')}`);

  for (const theme of themes) {
    console.log(`\n\nProcessing Theme: [${theme}]`);

    console.log('  - Compiling color modes...');
    for (const mode of COLOR_MODES) {
      try {
        const sources = COLOR_COLLECTIONS.flatMap(collection =>
          getSourceFilesForCollection(collection, theme, collection === 'primitives' ? 'value' : collection === 'semantics' ? 'base' : mode)
        ); 
        await compileTempMode(sources, path.join(TEMP_DIR, `${theme}-${mode}.css`));
      } catch (error) {
        console.warn(`    - ⚠️  Compilation failed for color mode '${mode}' in theme '${theme}'.`);
      }
    }

    console.log('  - Compiling size modes...');
    for (const mode of BREAKPOINT_MODES) {
      try {
        const sources = SIZE_COLLECTIONS.flatMap(collection =>
          getSourceFilesForCollection(collection, theme, collection === 'primitives' ? 'value' : mode)
        );
        await compileTempMode(sources, path.join(TEMP_DIR, `${theme}-${mode}.css`));
      } catch (error) {
        console.warn(`    - ⚠️  Compilation failed for size mode '${mode}' in theme '${theme}'.`);
      }
    }

    console.log('  - Compiling typography modes...');
    for (const mode of BREAKPOINT_MODES) {
      try {
        const sources = TYPOGRAPHY_COLLECTIONS.flatMap(collection =>
          getSourceFilesForCollection(collection, theme, collection === 'primitives' ? 'value' : mode)
        );
        await compileTempMode(sources, path.join(TEMP_DIR, `${theme}-${mode}-typography.css`));
      } catch (error) {
        console.warn(`    - ⚠️  Compilation failed for typography mode '${mode}' in theme '${theme}'.`);
      }
    }

    synthesizeColorCss(theme);
    synthesizeSizeCss(theme);
    synthesizeTypographyCss(theme);
  }

  console.log('\n\n🧱 Building mix-and-match building blocks...');
  for (const theme of themes) {
    console.log(`\nProcessing Building Blocks for Theme: [${theme}]`);
    await compilePrimitivesBuildingBlock(theme);
    await compilePaletteBuildingBlock(theme);
    await compileSizeBuildingBlock(theme);
    await compileTypographyBuildingBlock(theme);
  }
  await compileSemanticsBuildingBlock();

  fs.rmSync(TEMP_DIR, { recursive: true, force: true });
  console.log('\n\n✅ Build complete. Temporary files cleaned up.');
  console.log(`🎉 Final CSS files are available in: ${OUTPUT_DIR}`);
}

main().catch(error => {
  console.error('\n❌ A critical error occurred during the build process:');
  console.error(error);
  process.exit(1);
});

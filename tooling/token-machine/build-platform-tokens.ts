import fs from 'node:fs';
import path from 'node:path';
import StyleDictionary from 'style-dictionary';

// --- Configuration ---
const DIST_DIR = path.join(process.cwd(), 'dist');

// --- Utilities ---
function ensureDir(filePath: string) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function toCamelCase(str: string) {
  return str.split('-').reduce((acc, part, i) => {
    if (i === 0) return acc + part.toLowerCase();
    return acc + part.charAt(0).toUpperCase() + part.slice(1).toLowerCase();
  }, '');
}

// Aggressively dig out the value whether it's transformed, raw W3C, or nested
function extractValue(token: any): any {
  if (!token) return undefined;
  return token.value ?? token.$value ?? token.original?.value ?? token.original?.$value;
}

function cleanTokenObject(obj: any): any {
  if (typeof obj !== 'object' || obj === null) return obj;
  const val = extractValue(obj);
  if (val !== undefined) return val; 
  const res: any = {};
  for (const key in obj) {
    res[key] = cleanTokenObject(obj[key]);
  }
  return res;
}

// --- Platform Generators ---

function generateCSS(theme: string, modes: string[], dictionaries: Record<string, any[]>, baseCache: Record<string, any[]>) {
  const defaultMode = modes[0];
  const darkKey = modes.find(m => m.toLowerCase() === 'dark');

  // Use the default theme as the source of truth for the API surface
  const apiSurfaceTokens = baseCache[defaultMode] || dictionaries[defaultMode] || [];

  const getSafeValue = (mode: string, token: any) => {
    // 1. Try exact mode in current theme
    let t = (dictionaries[mode] || []).find(x => x.name === token.name);
    let val = extractValue(t);
    
    // 2. Try default mode in current theme
    if (val === undefined || val === null || val === '') {
       t = (dictionaries[defaultMode] || []).find(x => x.name === token.name);
       val = extractValue(t);
    }
    
    // 3. Fall back to Base/Default theme cache
    if (val === undefined || val === null || val === '') {
      t = (baseCache[mode] || baseCache[defaultMode] || []).find(x => x.name === token.name) || token;
      val = extractValue(t);
    }
    return val;
  };

  let css = `/* dist/${theme}/css/theme.css */\n`;
  css += `/* Automatically generated by build-platform-tokens.ts */\n\n`;

  css += `/* 1. Base / Default Mode Tokens (${defaultMode}) */\n`;
  css += `:root {\n`;
  apiSurfaceTokens.forEach(token => {
    css += `  --${token.name}: ${getSafeValue(defaultMode, token)};\n`;
  });
  css += `}\n\n`;

  if (darkKey) {
    css += `/* 2. OS Media Query Fallback (dark) */\n`;
    css += `@media (prefers-color-scheme: dark) {\n`;
    css += `  :root {\n`;
    apiSurfaceTokens.forEach(token => {
      css += `    --${token.name}: ${getSafeValue(darkKey, token)};\n`;
    });
    css += `  }\n}\n\n`;
  }

  css += `/* 3. Agnostic Data-Attribute Triggers */\n`;
  for (const mode of modes) {
    css += `:root[data-mode="${mode.toLowerCase()}"] {\n`;
    apiSurfaceTokens.forEach(token => {
      css += `  --${token.name}: ${getSafeValue(mode, token)};\n`;
    });
    css += `}\n\n`;
  }

  const outPath = path.join(DIST_DIR, theme, 'css', 'theme.css');
  ensureDir(outPath);
  fs.writeFileSync(outPath, css);
  console.log(`  \x1b[32m✓ Created CSS \x1b[90m(theme.css)\x1b[0m`);
}

function generateJS(theme: string, modes: string[], rawModes: Record<string, any>) {
  let js = `// dist/${theme}/js/theme.js\n// Automatically generated\n\n`;

  for (const mode of modes) {
    const safeModeName = mode.replace(/[-_](.)/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9]/g, '');
    const cleanObj = cleanTokenObject(rawModes[mode] || {});
    js += `export const ${safeModeName} = ${JSON.stringify(cleanObj, null, 2)};\n\n`;
  }

  const outPath = path.join(DIST_DIR, theme, 'js', 'theme.js');
  ensureDir(outPath);
  fs.writeFileSync(outPath, js);
  console.log(`  \x1b[32m✓ Created JS \x1b[90m(theme.js)\x1b[0m`);
}

function generateSwift(theme: string, modes: string[], dictionaries: Record<string, any[]>, baseCache: Record<string, any[]>) {
  const baseTokens = baseCache[modes[0]] || dictionaries[modes[0]] || [];
  const colorTokens = baseTokens.filter(t => t.$type === 'color' || t.type === 'color');
  const sizeTokens = baseTokens.filter(t => t.$type === 'dimension' || t.type === 'dimension' || t.$type === 'number');

  let swift = `// dist/${theme}/swift/ZebraTokens.swift\n// Automatically generated\n\nimport SwiftUI\n\n`;

  swift += `public struct ZebraColors {\n`;
  swift += `    public var modeOverride: String?\n\n`;
  swift += `    public init(modeOverride: String? = nil) {\n`;
  swift += `        self.modeOverride = modeOverride\n`;
  swift += `    }\n\n`;
  swift += `    @Environment(\\.colorScheme) var colorScheme\n\n`;
  swift += `    private var currentMode: String {\n`;
  swift += `        if let mode = modeOverride { return mode }\n`;
  swift += `        return colorScheme == .dark ? "dark" : "${modes[0].toLowerCase()}"\n`;
  swift += `    }\n\n`;

  for (const token of colorTokens) {
    const camelName = toCamelCase(token.name);
    swift += `    public var ${camelName}: Color {\n`;
    swift += `        switch currentMode {\n`;
    for (const mode of modes) {
      let modeToken = (dictionaries[mode] || []).find(t => t.name === token.name);
      let val = extractValue(modeToken);
      
      // Smart Fallback hierarchy
      if (!val || typeof val !== 'string' || val.trim() === '') {
        modeToken = (dictionaries[modes[0]] || []).find(t => t.name === token.name);
        val = extractValue(modeToken);
      }
      if (!val || typeof val !== 'string' || val.trim() === '') {
        modeToken = (baseCache[mode] || baseCache[modes[0]] || []).find(t => t.name === token.name) || token;
        val = extractValue(modeToken);
      }
      
      const hexValue = (typeof val === 'string') ? val : '#FFFFFF';
      swift += `        case "${mode.toLowerCase()}": return Color(hex: "${hexValue}")\n`;
    }
    const defaultVal = extractValue(token);
    const defaultHex = (typeof defaultVal === 'string') ? defaultVal : '#FFFFFF';
    swift += `        default: return Color(hex: "${defaultHex}")\n`;
    swift += `        }\n    }\n`;
  }
  swift += `}\n\n`;

  swift += `public struct ZebraDimensions {\n`;
  for (const token of sizeTokens) {
    const camelName = toCamelCase(token.name);
    const rawVal = extractValue(token);
    const val = parseFloat(rawVal);
    swift += `    public static let ${camelName}: CGFloat = ${isNaN(val) ? 0 : val}\n`;
  }
  swift += `}\n\n`;

  swift += `// Helper to parse hex strings natively
extension Color {
    init(hex: String) {
        let hex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        var int: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&int)
        let a, r, g, b: UInt64
        switch hex.count {
        case 3: (a, r, g, b) = (255, (int >> 8) * 17, (int >> 4 & 0xF) * 17, (int & 0xF) * 17)
        case 6: (a, r, g, b) = (255, int >> 16, int >> 8 & 0xFF, int & 0xFF)
        case 8: (a, r, g, b) = (int >> 24, int >> 16 & 0xFF, int >> 8 & 0xFF, int & 0xFF)
        default: (a, r, g, b) = (255, 0, 0, 0)
        }
        self.init(.sRGB, red: Double(r) / 255, green: Double(g) / 255, blue:  Double(b) / 255, opacity: Double(a) / 255)
    }
}\n`;

  const outPath = path.join(DIST_DIR, theme, 'swift', 'ZebraTokens.swift');
  ensureDir(outPath);
  fs.writeFileSync(outPath, swift);
  console.log(`  \x1b[32m✓ Created SwiftUI \x1b[90m(ZebraTokens.swift)\x1b[0m`);
}

function generateFlutter(theme: string, modes: string[], dictionaries: Record<string, any[]>, baseCache: Record<string, any[]>) {
  const baseTokens = baseCache[modes[0]] || dictionaries[modes[0]] || [];
  const colorTokens = baseTokens.filter(t => t.$type === 'color' || t.type === 'color');
  const sizeTokens = baseTokens.filter(t => t.$type === 'dimension' || t.type === 'dimension' || t.$type === 'number');

  let dart = `// dist/${theme}/flutter/zebra_tokens.dart\n// Automatically generated\n\nimport 'package:flutter/material.dart';\n\n`;

  dart += `class ZebraColorsThemeExtension extends ThemeExtension<ZebraColorsThemeExtension> {\n`;

  for (const token of colorTokens) {
    dart += `  final Color? ${toCamelCase(token.name)};\n`;
  }

  dart += `\n  const ZebraColorsThemeExtension({\n`;
  for (const token of colorTokens) {
    dart += `    this.${toCamelCase(token.name)},\n`;
  }
  dart += `  });\n\n`;

  dart += `  @override\n  ThemeExtension<ZebraColorsThemeExtension> copyWith({\n`;
  for (const token of colorTokens) dart += `    Color? ${toCamelCase(token.name)},\n`;
  dart += `  }) {\n    return ZebraColorsThemeExtension(\n`;
  for (const token of colorTokens) {
    const name = toCamelCase(token.name);
    dart += `      ${name}: ${name} ?? this.${name},\n`;
  }
  dart += `    );\n  }\n\n`;

  dart += `  @override\n  ThemeExtension<ZebraColorsThemeExtension> lerp(\n    covariant ThemeExtension<ZebraColorsThemeExtension>? other,\n    double t,\n  ) {\n`;
  dart += `    if (other is! ZebraColorsThemeExtension) { return this; }\n    return ZebraColorsThemeExtension(\n`;
  for (const token of colorTokens) {
    const name = toCamelCase(token.name);
    dart += `      ${name}: Color.lerp(${name}, other.${name}, t),\n`;
  }
  dart += `    );\n  }\n\n`;

  for (const mode of modes) {
    dart += `  static final ${toCamelCase(mode)} = ZebraColorsThemeExtension(\n`;
    for (const token of colorTokens) {
      let modeToken = (dictionaries[mode] || []).find(t => t.name === token.name);
      let val = extractValue(modeToken);
      
      if (!val || typeof val !== 'string' || val.trim() === '') {
        modeToken = (dictionaries[modes[0]] || []).find(t => t.name === token.name);
        val = extractValue(modeToken);
      }
      if (!val || typeof val !== 'string' || val.trim() === '') {
        modeToken = (baseCache[mode] || baseCache[modes[0]] || []).find(t => t.name === token.name) || token;
        val = extractValue(modeToken);
      }
      
      const rawVal = (typeof val === 'string') ? val : '#FFFFFF';
      const hexStr = rawVal.replace('#', '');
      const argb = hexStr.length === 6 ? `0xFF${hexStr}` : `0x${hexStr}`;
      
      dart += `    ${toCamelCase(token.name)}: const Color(${argb}),\n`;
    }
    dart += `  );\n`;
  }
  dart += `}\n\n`;

  dart += `class ZebraDimensions {\n`;
  for (const token of sizeTokens) {
    const rawVal = extractValue(token);
    const val = parseFloat(rawVal);
    dart += `  static const double ${toCamelCase(token.name)} = ${isNaN(val) ? 0 : val};\n`;
  }
  dart += `}\n`;

  const outPath = path.join(DIST_DIR, theme, 'flutter', 'zebra_tokens.dart');
  ensureDir(outPath);
  fs.writeFileSync(outPath, dart);
  console.log(`  \x1b[32m✓ Created Flutter \x1b[90m(zebra_tokens.dart)\x1b[0m`);
}

// --- Main Build Execution ---

(async () => {
  console.log(`\x1b[1m\x1b[34m\n🚀 Zebra Platform Tokens Compiler (SD v4)\n\x1b[0m`);

  const cwd = process.cwd();
  const tokensDirPath = path.join(cwd, 'tokens');

  if (!fs.existsSync(tokensDirPath)) {
    console.error("❌ Tokens directory not found.");
    process.exit(1);
  }

  const entries = fs.readdirSync(tokensDirPath, { withFileTypes: true });
  
  const themes = entries
    .filter(ent => ent.isDirectory() && ent.name !== 'core')
    .map(ent => ent.name)
    .sort((a, b) => {
      if (a === 'default') return -1;
      if (b === 'default') return 1;
      return a.localeCompare(b);
    });

  let globalBaseThemeCache: Record<string, any[]> = {};

  for (const theme of themes) {
    console.log(`\n\x1b[36m📦 Processing Theme: ${theme}\x1b[0m`);
    const themeDir = path.join(tokensDirPath, theme);
    
    const modeFiles = fs.readdirSync(themeDir).filter(f => f.endsWith('.json'));
    const modes = modeFiles.map(f => f.replace('.json', '')).sort(); 

    if (modes.length === 0) continue;

    const resolvedModes: Record<string, any[]> = {};
    const rawModes: Record<string, any> = {}; 

    for (const mode of modes) {
      console.log(`  \x1b[90m⚙️ Resolving mode references: ${mode}...\x1b[0m`);

      // MUST use relative paths for reliable globbing in fast-glob/StyleDictionary v4
      const sources: string[] = [];
      
      if (fs.existsSync(path.join(cwd, 'tokens/primitives.json'))) sources.push('tokens/primitives.json');
      if (fs.existsSync(path.join(cwd, 'tokens/semantics.json'))) sources.push('tokens/semantics.json');

      if (theme !== 'default') {
        const defaultModePath = `tokens/default/${mode}.json`;
        const fallbackLightPath = `tokens/default/Light.json`;
        
        if (fs.existsSync(path.join(cwd, defaultModePath))) sources.push(defaultModePath);
        else if (fs.existsSync(path.join(cwd, fallbackLightPath))) sources.push(fallbackLightPath);
      }

      sources.push(`tokens/${theme}/${mode}.json`);

      const sd = new StyleDictionary({
        source: sources,
        log: {
          warnings: 'disabled',
          errors: { brokenReferences: 'warning' }
        },
        platforms: {
          css: {
            transformGroup: 'css',
            options: { allowUndefined: true }
          }
        }
      });

      await sd.hasInitialized;
      
      const dictionary = await sd.getPlatformTokens('css');
      resolvedModes[mode] = dictionary?.allTokens || [];
      rawModes[mode] = dictionary?.tokens || {}; 
    }

    if (theme === 'default') {
      globalBaseThemeCache = { ...resolvedModes };
    }

    generateCSS(theme, modes, resolvedModes, globalBaseThemeCache);
    generateJS(theme, modes, rawModes);
    generateSwift(theme, modes, resolvedModes, globalBaseThemeCache);
    generateFlutter(theme, modes, resolvedModes, globalBaseThemeCache);
  }

  console.log(`\x1b[1m\x1b[32m\n✨ All native platform assets compiled successfully!\n\x1b[0m`);
})();

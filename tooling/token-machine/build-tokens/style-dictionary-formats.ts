StyleDictionary.registerFormat({
  name: 'flutter/bb-impl',
  format: async ({ dictionary, options }) => {
    const {
      interfaceName, interfaceImportPath, className,
      ctorParamName, ctorParamType, ctorParamImportPath, needsMaterialImport,
    } = options as any;

    const imports: string[] = [];
    if (needsMaterialImport) imports.push(`import 'package:flutter/material.dart';`);
    imports.push(`import '${interfaceImportPath}';`);
    if (ctorParamImportPath) imports.push(`import '${ctorParamImportPath}';`);

    let code = `// Auto-generated. Do not edit directly.\n\n${imports.join('\n')}\n\nclass ${className} implements ${interfaceName} {\n`;
    if (ctorParamName) {
      code += `  final ${ctorParamType} ${ctorParamName};\n\n  const ${className}(this.${ctorParamName});\n\n`;
    } else {
      code += `  const ${className}();\n\n`;
    }

    dictionary.allTokens.forEach(token => {
      const memberName = dashToCamel(token.path.slice(1).join('-'));
      const originalValue = token.original.$value;
      let dartType: string, expr: string;

      if (ctorParamName && usesReferences(originalValue)) {
        const refs = getReferences(originalValue, dictionary.tokenMap, { unfilteredTokens: dictionary.unfilteredTokenMap });
        if (refs.length > 0) {
          const refMemberName = dashToCamel(refs[0].path.slice(1).join('-'));
          dartType = 'dynamic';
          expr = `${ctorParamName}.${refMemberName}`;
        } else {
          ({ dartType, expr } = dartValueLiteral(token.$value));
        }
      } else {
        ({ dartType, expr } = dartValueLiteral(token.$value));
      }

      code += `  @override\n  ${dartType} get ${memberName} => ${expr};\n`;
    });

    code += `}\n`;
    return code;
  },
});

StyleDictionary.registerFormat({
  name: 'javascript/object-entries',
  format: async ({ dictionary, options }) => {
    const ctorParamName = (options as any)?.ctorParamName;
    const entries = dictionary.allTokens.map(token => {
      const key = dashToCamel(token.name.substring(token.name.indexOf('-') + 1));
      if (ctorParamName && usesReferences(token.original.$value)) {
        const refs = getReferences(token.original.$value, dictionary.tokenMap, { unfilteredTokens: dictionary.unfilteredTokenMap });
        if (refs.length > 0) {
          const refKey = dashToCamel(refs[0].name.substring(refs[0].name.indexOf('-') + 1));
          return `  ${key}: ${ctorParamName}.${refKey},`;
        }
      }
      return `  ${key}: ${JSON.stringify(token.$value)},`;
    }).join('\n');
    return `{\n${entries}\n}`;
  },
});

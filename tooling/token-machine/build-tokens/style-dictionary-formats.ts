import StyleDictionary, { type TransformedToken } from 'style-dictionary';
import { dashToCamel } from './utils.js';

// Font-family values need a sans-serif fallback; skip it if the value already has one.
function appendSansSerifFallback(value: unknown): unknown {
  return typeof value === 'string' && !value.includes('sans-serif') ? `${value}, sans-serif` : value;
}

StyleDictionary.registerFilter({
  name: 'encapsulationFilter',
  filter: (token: TransformedToken) => {
    const collection = token.path[0];
    return ['semantics', 'size', 'typography'].includes(collection);
  },
});

function renderCssVariables(dictionary: { allTokens: TransformedToken[] }): string {
  const header = `/**\n * Do not edit directly.\n * This file was auto-generated by the Design Token build script.\n */\n`;
  const variables = dictionary.allTokens.map(token => {
    const tokenName = token.name.substring(token.name.indexOf('-') + 1);
    const value = tokenName.includes('font-family') ? appendSansSerifFallback(token.$value) : token.$value;
    return `  --${tokenName}: ${value};`;
  }).join('\n');
  return `${header}:root {\n${variables}\n}\n`;
}

// Same renderer under two names: 'css/variables-root' flattens references to literal values,
// 'css/variables' (used with outputReferences: true) keeps var() references - the difference
// is in how Style Dictionary resolves token.$value before it gets here, not in this format.
StyleDictionary.registerFormat({ name: 'css/variables-root', format: async ({ dictionary }) => renderCssVariables(dictionary) });
StyleDictionary.registerFormat({ name: 'css/variables', format: async ({ dictionary }) => renderCssVariables(dictionary) });

['primitives', 'palette', 'semantics', 'size', 'typography'].forEach(collection => {
  StyleDictionary.registerFilter({
    name: `${collection}OnlyFilter`,
    filter: (token: TransformedToken) => token.path[0] === collection,
  });
});

StyleDictionary.registerFormat({
  name: 'json/flat-entries',
  format: async ({ dictionary }) => {
    const obj: Record<string, any> = {};
    // Typography properties that should be kept with dashes
    const typographyProps = new Set(['font-family', 'font-size', 'font-weight', 'line-height', 'letter-spacing']);

    for (const token of dictionary.allTokens) {
      // Remove the collection prefix (e.g., "color-", "size-", "typography-")
      const nameWithoutPrefix = token.name.substring(token.name.indexOf('-') + 1);

      // Split on dashes to get the path segments
      let segments = nameWithoutPrefix.split('-');

      // For typography tokens, preserve property names with dashes (font-family, line-height, etc.)
      if (token.name.startsWith('typography-')) {
        // Check if last segment or last two segments form a typography property
        const lastSegment = segments[segments.length - 1];
        const lastTwo = segments.slice(-2).join('-');

        if (typographyProps.has(lastTwo)) {
          // Combine last two segments back into one (e.g., 'line' + 'height' → 'line-height')
          segments = [...segments.slice(0, -2), lastTwo];
        }
      }

      // Build nested object structure
      let current = obj;
      for (let i = 0; i < segments.length - 1; i++) {
        const segment = dashToCamel(segments[i]);
        if (!current[segment]) {
          current[segment] = {};
        }
        current = current[segment];
      }

      // Use the token's $type if available, otherwise infer it
      let type = token.$type;
      if (!type || type === 'unknown') {
        // Infer type from the value if $type is missing or invalid
        if (typeof token.$value === 'object' && token.$value !== null) {
          if ('r' in token.$value && 'g' in token.$value && 'b' in token.$value) {
            type = 'color';
          } else {
            type = 'object';
          }
        } else if (typeof token.$value === 'string') {
          // Try to infer from string value
          if (/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(token.$value)) {
            type = 'color';
          } else if (/^[\d.]+(?:px|em|rem|%|pt|cm|mm|in|ch|ex|vw|vh|vmin|vmax)$/i.test(token.$value)) {
            type = 'dimension';
          } else if (/^[\d.]+(?:ms|s)$/i.test(token.$value)) {
            type = 'duration';
          } else if (/^[\d.]+$/i.test(token.$value) && token.name.includes('weight')) {
            type = 'fontWeight';
          } else {
            type = 'string';
          }
        } else if (typeof token.$value === 'number') {
          if (token.name.includes('weight')) type = 'fontWeight';
          else if (token.name.includes('opacity')) type = 'number';
          else type = 'number';
        } else if (typeof token.$value === 'boolean') {
          type = 'boolean';
        } else {
          type = 'string';
        }
      }

      // Set the final value as a DTCG token object with $type and $value
      // Keep the last segment as-is if it's a typography property (with dash), otherwise dashToCamel
      const lastSegment = segments[segments.length - 1];
      const finalKey = typographyProps.has(lastSegment) ? lastSegment : dashToCamel(lastSegment);
      const value = lastSegment === 'font-family' ? appendSansSerifFallback(token.$value) : token.$value;

      current[finalKey] = {
        $type: type,
        $value: value,
      };
    }
    return JSON.stringify(obj, null, 2);
  },
});

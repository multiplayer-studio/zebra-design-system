StyleDictionary.registerFormat({
  name: 'flutter/flat-typography',
  format: async ({ dictionary, options }) => {
    const className = (options as any).className;
    const mode = (options as any).mode || '';

    const grouped: Record<string, Record<string, TransformedToken>> = {};
    dictionary.allTokens.forEach(token => {
      const leaf = token.path[token.path.length - 1];
      const groupKey = token.path.slice(1, -1).join('-');
      if (!grouped[groupKey]) grouped[groupKey] = {};
      grouped[groupKey][leaf] = token;
    });

    let code = `// Generated design tokens for ${mode} breakpoint\n// Do not edit directly.\n\nimport 'package:flutter/material.dart';\n\nclass ${className} {\n`;
    Object.entries(grouped).forEach(([groupKey, props]) => {
      const memberName = dashToCamel(groupKey);
      const fontFamily = props.fontfamily?.$value;
      const fontSize = props.fontsize?.$value !== undefined ? parseFloat(String(props.fontsize.$value)) : undefined;
      const lineHeight = props.lineheight?.$value !== undefined ? parseFloat(String(props.lineheight.$value)) : undefined;
      const letterSpacing = props.letterspacing?.$value !== undefined ? parseFloat(String(props.letterspacing.$value)) : undefined;
      const fontWeight = props.fontweight?.$value !== undefined ? Number(props.fontweight.$value) : undefined;

      const parts: string[] = [];
      if (fontFamily !== undefined) parts.push(`fontFamily: '${String(fontFamily).replace(/'/g, "\\'")}'`);
      if (fontSize !== undefined) parts.push(`fontSize: ${fontSize}`);
      if (fontWeight !== undefined) parts.push(`fontWeight: FontWeight.w${fontWeight}`);
      if (lineHeight !== undefined && fontSize !== undefined) parts.push(`height: ${(lineHeight / fontSize).toFixed(2)}`);
      if (letterSpacing !== undefined) parts.push(`letterSpacing: ${letterSpacing}`);

      code += `  static final TextStyle ${memberName} = const TextStyle(${parts.join(', ')});\n`;
    });
    code += `}\n`;
    return code;
  },
});

